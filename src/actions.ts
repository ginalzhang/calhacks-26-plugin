/**
 * Steady action table: the single source for tiles, global keys, the voice grammar,
 * the typed-command box, Cartesia keyterms and the Krita dispatch map.
 *
 * SHARED CONTRACT. ONLY THE LEAD EDITS THIS FILE. Subagents request new rows or
 * changes in DECISIONS.md ("Action table requests"); the lead merges them.
 *
 * Rules (§0 rule 4, §6):
 * - Every action is reachable by a tile, a voice phrase and a typed command (same grammar).
 *   Exceptions: `mic` and `pen_toggle` have `voicePhrases: []` and `typed: null`.
 * - `key` is non-null iff the action is one of the §4 core actions (F3–F10).
 * - `phase` is when the voice/typed row lands in the grammar. `tilePhase` (if set) is
 *   when the tile/key exists; a tile whose phase has not landed renders DISABLED with its
 *   label, never absent.
 * - `fuzzyAllowed` is false for every mode-changing action and for every phrase < 5 chars
 *   (the grammar also enforces the length rule itself).
 * - Typed box: matches `typed` forms AND voice phrases. Voice: matches voice phrases only.
 */
import type { KritaCommand } from "./desktop/protocol";

export type Scope = "canvas" | "krita" | "both";
export type Phase = "P0" | "P1" | "P2a" | "P2b" | "P3" | "P4";
export const PHASE_ORDER: Phase[] = ["P0", "P1", "P2a", "P2b", "P3", "P4"];

/** Side-panel page a tile lives on. "header" = pinned header. "dialog" = only shown inside dialogs/clarify. */
export type PageId =
  | "header"
  | "steady"
  | "setup"
  | "timing"
  | "demo"
  | "paint"
  | "colour"
  | "view"
  | "layers"
  | "dialog";

export interface KritaDispatch {
  /** Command sent through the plugin when it is connected. */
  plugin?: KritaCommand;
  /** Keystroke fallback when the plugin is down (macOS Krita defaults). */
  keys?: string;
  /** Action id must be looked up at runtime via list_actions, matching this text (case-insensitive). Never guess an id. */
  lookupText?: string;
  /** True when there is no keystroke fallback: say "That needs the Krita plugin" if the plugin is down. */
  pluginOnly?: boolean;
  /** Choosing this also clears the erase toggle (brush/pencil/ink/airbrush). */
  clearsEraser?: boolean;
}

export interface Action {
  id: string;
  /** Visible tile label (≥ 18 px text). */
  label: string;
  /** Voice phrases, primary first. [] only for `mic` and `pen_toggle`. */
  voicePhrases: string[];
  /** Typed-box form (primary). null only for `mic` and `pen_toggle`. */
  typed: string | null;
  /** §4 global key, or null. */
  key: string | null;
  scope: Scope;
  /** When the voice/typed row lands. */
  phase: Phase;
  /** When the tile/key lands, if earlier than `phase`. */
  tilePhase?: Phase;
  destructive: boolean;
  fuzzyAllowed: boolean;
  /** Changes a mode (latch, dots, hatch, ...). Never fuzzy-matched. */
  modeChanging?: boolean;
  /** Takes an argument: a number ("size 20", "opacity fifty") or one word ("alias fluffy", "call this brush fluffy"). */
  arg?: "number" | "word";
  /** Tile is a toggle exposing aria-pressed (fixed name). */
  toggle?: boolean;
  page: PageId;
  /** Per-phrase variant for actions with several meanings (pause: "stop" → "pause", "resume" → "resume"). */
  phraseVariants?: Record<string, string>;
  /** Krita dispatch for scope krita/both. */
  krita?: KritaDispatch;
  /** Short Help text. Never names a condition (§0 rule 11). */
  help?: string;
}

