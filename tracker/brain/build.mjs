// Bundle the Steady brain: tracker/brain/brain.ts → tracker/brain/dist/brain.mjs
// (platform node, ESM, node20, every dependency inlined; only node builtins stay external).
// Run: npm run brain:build
import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));

await build({
  entryPoints: [path.join(here, "brain.ts")],
  outfile: path.join(here, "dist", "brain.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  packages: "bundle",
  sourcemap: false,
  legalComments: "none",
  logLevel: "warning",
  banner: {
    js: [
      "// Steady brain bundle. GENERATED by tracker/brain/build.mjs from tracker/brain/brain.ts — do not edit.",
      'import { createRequire as __steadyCreateRequire } from "node:module";',
      "const require = __steadyCreateRequire(import.meta.url);",
    ].join("\n"),
  },
});

console.log(`built ${path.relative(process.cwd(), path.join(here, "dist", "brain.mjs"))}`);
